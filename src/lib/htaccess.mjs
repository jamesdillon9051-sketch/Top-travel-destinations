/**
 * Web-server configuration for Apache / LiteSpeed shared hosting (Hostinger).
 *
 * The site is plain static files in docs/. How those files reach the web root
 * depends on how the host deploys the repository, so build.mjs writes two
 * files from this one module, and scripts/check-deploy.mjs fails if either
 * ever drifts from it:
 *
 *   docs/.htaccess   for hosts where docs/ itself is the web root. It is also
 *                    present (and takes over) when the whole repo is deployed,
 *                    because Apache applies the nearest .htaccess.
 *   .htaccess        for hosts that copy the whole repo into public_html — it
 *                    serves docs/ as the site root and hides everything else.
 *
 * Everything except the two small rewrite extras is shared. Every directive
 * that depends on an optional Apache module sits inside an <IfModule> guard,
 * so a host without that module ignores it instead of answering 500.
 */

const escapeRegex = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const HEADER = `# Generated by build.mjs from src/lib/htaccess.mjs - edit that file, not this one.`;

/** Directives that apply no matter where the files are served from. */
function core() {
  return String.raw`Options -Indexes
DirectoryIndex index.html
AddDefaultCharset UTF-8
ErrorDocument 404 /404.html

<IfModule mod_mime.c>
  AddType image/webp .webp
  AddType font/woff2 .woff2
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml application/xml application/javascript text/javascript image/svg+xml
</IfModule>

# Images change rarely, so a month keeps repeat visits fast. CSS and JS are not
# fingerprinted, so they get a short lifetime and edits show up within the hour.
<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/webp "access plus 1 month"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/css "access plus 1 hour"
  ExpiresByType application/javascript "access plus 1 hour"
  ExpiresByType text/javascript "access plus 1 hour"
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
</IfModule>`;
}

/**
 * A 301 whose target is built differently for the real domain and for any
 * other hostname. On the real domain it always lands on https://<domain>/…,
 * even when a TLS-terminating proxy makes Apache think the request was plain
 * http; on previews and local servers it stays a path-only redirect.
 *
 * `conds` must end with the condition that owns any %1 backreference.
 */
function redirect301({ domain, conds = [], pattern, path }) {
  const lines = (prefix, target) =>
    [...prefix, ...conds, `RewriteRule ${pattern} ${target} [R=301,L]`].join('\n');
  const generic = lines([], path);
  if (!domain) return generic;
  const canonical = lines(
    [`RewriteCond %{HTTP_HOST} ^${escapeRegex(domain)}$ [NC]`],
    `https://${domain}${path}`
  );
  return `${canonical}\n${generic}`;
}

/** The https / no-www redirect. Limited to the real domain so preview hostnames still work. */
function canonicalHost(domain) {
  if (!domain) return '';
  const host = escapeRegex(domain);
  return String.raw`
# One canonical origin: https://${domain} (no www).
RewriteCond %{HTTP_HOST} ^www\.${host}$ [NC]
RewriteRule ^ https://${domain}%{REQUEST_URI} [R=301,L]
RewriteCond %{HTTP_HOST} ^${host}$ [NC]
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !https [NC]
RewriteRule ^ https://${domain}%{REQUEST_URI} [R=301,L]
`;
}

/** Rewrite rules, with optional extras (the per-variant block) slotted in last. */
function rewrites({ domain, extra = '' }) {
  return String.raw`<IfModule mod_rewrite.c>
RewriteEngine On

# Domain-validation (SSL) requests must reach the real folder untouched.
RewriteRule ^\.well-known/ - [L]

# Hidden files and folders (.git, .github, .gitignore, ...) are never public.
RewriteRule (^|/)\.(?!well-known(/|$)) - [F,L]
${canonicalHost(domain)}${extra}</IfModule>`;
}

/**
 * docs/.htaccess extra. When the whole repo is deployed, a request for
 * /docs/... lands inside docs/, so this file (not the root one) must send it
 * to the clean URL instead of serving a duplicate copy of every page.
 */
function docsPathRedirect(domain) {
  return `
# The site is served from the web root: /docs/... is not a public URL.
${redirect301({
  domain,
  conds: [String.raw`RewriteCond %{THE_REQUEST} \s/docs/(\S*)`],
  pattern: '^',
  path: '/%1'
})}
`;
}

/** Only used when the whole repo is deployed to the web root: serve docs/ as the site. */
function rootServesDocs(domain) {
  return String.raw`
# ---- Serve the built site (docs/) as the web root --------------------------
# Never serve the source tree, image masters or build tooling.
RewriteRule ^(?:src|content|scripts|node_modules)(?:/|$) - [F,L]
RewriteRule ^(?:build\.mjs|package(?:-lock)?\.json|README\.md|CNAME)$ - [F,L]

# A directory URL without its trailing slash gets one before it is mapped into docs/.
${redirect301({
  domain,
  conds: ['RewriteCond %{DOCUMENT_ROOT}/docs/$1 -d'],
  pattern: '^(.+[^/])$',
  path: '/$1/'
})}

# Everything else comes from docs/.
RewriteCond %{REQUEST_URI} !^/docs/
RewriteRule ^(.*)$ /docs/$1 [L]
`;
}

/** docs/.htaccess — docs/ is the web root (and the nearest config when the repo is). */
export function docsHtaccess({ domain } = {}) {
  return `${HEADER}\n\n${core()}\n\n${rewrites({ domain, extra: docsPathRedirect(domain) })}\n`;
}

/** .htaccess at the repo root — the whole repo is the web root. */
export function rootHtaccess({ domain } = {}) {
  return `${HEADER}\n\n${core()}\n\n${rewrites({ domain, extra: rootServesDocs(domain) })}\n`;
}
